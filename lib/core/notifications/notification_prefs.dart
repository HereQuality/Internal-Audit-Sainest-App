  /// True while this device still holds an explicit "Notifications: off"
  /// that hasn't been carried over to the account yet. The old switch
  /// defaulted ON, so only a stored `false` counts as a choice.
  static Future<bool> readLegacyPushOptOut() async {
    final prefs = await SharedPreferences.getInstance();
    if (prefs.getBool(_legacyMigratedKey) ?? false) return false;
    return prefs.getBool(_legacyBgPollingKey) == false;
  }

  /// Drops every retired key and marks the migration done so it never
  /// runs (or re-reads a stale opt-out) again.
  static Future<void> finishLegacyMigration() async {
    final prefs = await SharedPreferences.getInstance();
    for (final key in _legacyKeys) {
      await prefs.remove(key);
    }
    await prefs.setBool(_legacyMigratedKey, true);
  }

  /// Writes the new session — and, only when the account logging in is
  /// DIFFERENT from whoever was last signed in on this device, wipes every
  /// dedup set above first. Comparing against the OUTGOING userId (still
  /// on disk here since [clearSession] deliberately leaves it) is what
  /// lets a same-person re-login be told apart from an actual account
  /// switch; a first-ever login on this device (previousUserId null) has
  /// no dedup state to wipe either way.
  static Future<void> setSession({required String token, required String userId}) async {
    final prefs = await SharedPreferences.getInstance();
    final previousUserId = prefs.getString(_userIdKey);
    if (previousUserId != null && previousUserId != userId) {
      await prefs.remove(_notifiedIdsKey);
      await prefs.remove(_seenAuditIdsKey);
      await prefs.remove(_auditBaselineSeededKey);
      await prefs.remove(_notifiedAuditDatesKey);
      await prefs.remove(_seenNcIdsKey);
      await prefs.remove(_ncBaselineSeededKey);
      await prefs.remove(_ncLastStatusKey);
      await prefs.remove(_ledgerKey);
    }
    await prefs.setString(_tokenKey, token);
    await prefs.setString(_userIdKey, userId);
    // The app has just had this session accepted (a login, or /auth/me at
    // launch): whatever a poll was told earlier about it is history.
    await prefs.remove(_rejectedTokenKey);
  }

  /// Called on logout. Clears the token — a stopped background poll has
  /// nothing to authenticate with either way (see
  /// background_entrypoints.dart#stopBackgroundPolling) — the per-topic
  /// push mirror (see above) and "the server can push to this phone" (the
  /// token was just unregistered; the next sign-in proves it again), and
  /// leaves userId and every dedup set above untouched, so the NEXT
  /// [setSession] can tell whether it's the same person logging back in (keep
  /// the dedup state) or a different account on this shared device (wipe it).
  /// The refused-session note goes with the token: it is a verbatim copy of a
  /// JWT, and without a token to compare against it has no job left.
  static Future<void> clearSession() async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.remove(_tokenKey);
    await prefs.remove(_rejectedTokenKey);
    await prefs.remove(_pushTypesKey);
    await prefs.remove(_fcmReadyKey);
    await prefs.remove(_fcmDeliveryFailedKey);
  }

  static Future<String?> readToken() async {
    final prefs = await SharedPreferences.getInstance();
    // Same cross-isolate staleness as readPushEnabled above. The foreground
    // service's isolate lives for hours while the app logs out and in
    // (possibly as someone else) around it; without this it would keep
    // authenticating as, and deciding whether to stop for, the token it
    // loaded when its engine started.
    await prefs.reload();
    return prefs.getString(_tokenKey);
  }

  static Future<String?> readUserId() async {
    final prefs = await SharedPreferences.getInstance();
    // The service isolate outlives account switches, and the polls scope
    // their requests to this id (event_poll.dart): a stale one would fetch
    // the previous account's items.
    await prefs.reload();
    return prefs.getString(_userIdKey);
  }

  /// NC ids the overdue poll has handled — announced, or recorded silently
  /// (topic off, server pushing it, catch-up pass) — so the same overdue NC
  /// is never announced twice by the poll. What the server pushed for it is
  /// the banner ledger's business, not this set's.
  static Future<Set<String>> readNotifiedIds() async {
    final prefs = await SharedPreferences.getInstance();
    return (prefs.getStringList(_notifiedIdsKey) ?? const []).toSet();
  }

  static Future<void> addNotifiedIds(Iterable<String> ids) async {
    final prefs = await SharedPreferences.getInstance();
    final current = (prefs.getStringList(_notifiedIdsKey) ?? const []).toSet();
    current.addAll(ids);
    // Cap growth — only the most recent 500 ids are worth remembering;
    // an NC that old has long since been closed or re-surfaced anyway.
    final capped = current.length > 500 ? current.skip(current.length - 500).toSet() : current;
    await prefs.setStringList(_notifiedIdsKey, capped.toList());
  }

